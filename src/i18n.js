// Every string the interface shows, in French and English, plus locale-aware
// number and date formatting. Entries are either plain strings or functions
// of named variables (for plurals and agreement).

import { storage } from './storage.js';

const NBSP = ' ';
const MINUS = '−';

const WORDS = {
  fr: { fem: ['zéro', 'une', 'deux', 'trois', 'quatre', 'cinq', 'six', 'sept', 'huit', 'neuf', 'dix'],
        masc: ['zéro', 'un', 'deux', 'trois', 'quatre', 'cinq', 'six', 'sept', 'huit', 'neuf', 'dix'] },
  en: { fem: ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten'] },
};
const cap = s => s.charAt(0).toUpperCase() + s.slice(1);

let lang = initialLang();

function initialLang() {
  const saved = storage.get('lang');
  if (saved === 'fr' || saved === 'en') return saved;
  return (navigator.language || 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export const getLang = () => lang;
export const locale = () => (lang === 'fr' ? 'fr-FR' : 'en-GB');
export function setLang(next) { lang = next; storage.set('lang', next); }

export function nw(n, gender = 'fem') {
  const table = WORDS[lang][gender] || WORDS[lang].fem;
  return n >= 0 && n < table.length ? table[n] : String(n);
}

// Values that may be given per language ({ fr, en }) or as a plain string.
export function pick(value) {
  if (value && typeof value === 'object') return value[lang] ?? value.en ?? value.fr ?? '';
  return value ?? '';
}

export function t(key, vars = {}) {
  const entry = DICT[lang][key] ?? DICT.en[key];
  if (entry == null) return key;
  return typeof entry === 'function' ? entry(vars) : entry;
}

// ── Formatting ────────────────────────────────────────────────

const nf = (min, max) => new Intl.NumberFormat(locale(), { minimumFractionDigits: min, maximumFractionDigits: max });

export const fmt = {
  seconds: ms => `${nf(1, 1).format(ms / 1000)}${NBSP}s`,
  ms: ms => `${Math.round(ms)}${NBSP}ms`,
  cls: v => nf(2, 2).format(v),
  number: (v, digits = 0) => nf(0, digits).format(v),
  metric(metric, v) {
    if (v == null) return '—';
    return metric === 'lcp' ? fmt.seconds(v) : metric === 'inp' ? fmt.ms(v) : fmt.cls(v);
  },
  saving(metric, v) { return MINUS + fmt.metric(metric, Math.abs(v)); },
  delta(metric, v) { return (v < 0 ? MINUS : '+') + fmt.metric(metric, Math.abs(v)); },
  tick(metric, v) {
    if (metric === 'lcp') return `${nf(0, 1).format(v / 1000)}${NBSP}s`;
    if (metric === 'inp') return `${Math.round(v)}`;
    return nf(0, 2).format(v);
  },
  size(kb) {
    return kb >= 1000
      ? `${nf(1, 1).format(kb / 1000)}${NBSP}${lang === 'fr' ? 'Mo' : 'MB'}`
      : `${Math.round(kb)}${NBSP}${lang === 'fr' ? 'Ko' : 'KB'}`;
  },
  date: (d, opts = { day: 'numeric', month: 'long', year: 'numeric' }) => new Intl.DateTimeFormat(locale(), opts).format(d),
  dateShort: d => new Intl.DateTimeFormat(locale(), { day: 'numeric', month: 'short' }).format(d),
  month: d => new Intl.DateTimeFormat(locale(), { month: 'short' }).format(d).replace('.', ''),
  time: d => new Intl.DateTimeFormat(locale(), { hour: 'numeric', minute: '2-digit' }).format(d),
  // "aujourd'hui", "hier", "il y a 3 jours", "il y a 2 semaines".
  ago(d, now = new Date()) {
    const rtf = new Intl.RelativeTimeFormat(locale(), { numeric: 'auto' });
    const day = x => new Date(x.getFullYear(), x.getMonth(), x.getDate());
    const days = Math.round((day(now) - day(new Date(d))) / 864e5);
    return days < 14 ? rtf.format(-Math.max(0, days), 'day') : rtf.format(-Math.round(days / 7), 'week');
  },
};

